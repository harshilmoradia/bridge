import { Bar, BarChart, Cell, CartesianGrid, Legend, ResponsiveContainer, Tooltip, XAxis, YAxis } from 'recharts';
import { Card, CardContent, CardHeader, CardTitle } from '../components/ui/card';
import { Table, TableBody, TableCell, TableHead, TableHeader, TableRow } from '../components/ui/table';
import summaryJson from '../generated/evalSummary.json';
import {
    chartData, costLatencyData, differenceGates, falseAutoGates, formatCalls, formatCost, formatLatency, formatRatio, formatTokens, hasRunMetrics, metricRows, orderedPipelines, placeholderTiers,
    type EvalSummary, type Gate, type PipelineName,
} from '../lib/evalSummary';
import { Page } from './Pages';

const summary = summaryJson as EvalSummary;

// Colour-blind-safe (Okabe-Ito), readable on both the light and dark card backgrounds.
const COLORS: Record<PipelineName, string> = { rules: '#8a94a6', nano: '#0072B2', super: '#E69F00', tiered: '#009E73', ultra: '#CC79A7' };

const NOT_RUN = <span className="text-muted-foreground">not run yet</span>;
const NA = <span className="text-muted-foreground">n/a</span>;

function GateCard({ title, rule, gates }: { title: string; rule: string; gates: Gate[] }) {
    const failing = gates.filter(g => !g.pass);
    return (
        <Card>
            <CardHeader><CardTitle className="text-base">{title}</CardTitle></CardHeader>
            <CardContent className="space-y-2 text-sm">
                <p className="text-muted-foreground">{rule}</p>
                {gates.length === 0 ? <p>No pipeline has run yet.</p> : (
                    <ul className="space-y-1">
                        {gates.map(g => (
                            <li key={g.pipeline} className="flex items-center justify-between gap-2">
                                <span className="flex items-center gap-2"><span aria-hidden="true" className="h-2.5 w-2.5 rounded-full" style={{ background: COLORS[g.pipeline] }} />{g.pipeline}</span>
                                <span className={g.pass ? 'font-medium' : 'font-medium text-destructive'}>
                                    <span className="font-mono">{g.display}</span> <span aria-hidden="true">{g.pass ? '✓' : '✗'}</span> {g.pass ? 'pass' : 'fail'}
                                </span>
                            </li>
                        ))}
                    </ul>
                )}
                {failing.length > 0 && <p role="status" className="text-destructive">{failing.map(g => g.pipeline).join(', ')} {failing.length === 1 ? 'misses' : 'miss'} this gate.</p>}
            </CardContent>
        </Card>
    );
}

function MiniChart({ title, unit, data, format }: { title: string; unit: string; data: { pipeline: PipelineName; value: number }[]; format: (v: number) => string }) {
    return (
        <Card>
            <CardHeader><CardTitle className="text-base">{title}</CardTitle></CardHeader>
            <CardContent>
                <div role="img" aria-label={`Bar chart of ${title.toLowerCase()}: ${data.map(d => `${d.pipeline} ${format(d.value)}`).join(', ')}.`} className="h-48 w-full text-muted-foreground">
                    <ResponsiveContainer width="100%" height="100%">
                        <BarChart data={data} margin={{ top: 8, right: 8, bottom: 8, left: 0 }} accessibilityLayer={false}>
                            <CartesianGrid vertical={false} stroke="var(--border)" />
                            <XAxis dataKey="pipeline" tick={{ fill: 'currentColor', fontSize: 12 }} stroke="var(--border)" />
                            <YAxis unit={unit} tick={{ fill: 'currentColor', fontSize: 12 }} stroke="var(--border)" />
                            <Tooltip cursor={{ fill: 'var(--muted)' }} contentStyle={{ background: 'var(--card)', border: '1px solid var(--border)', color: 'var(--foreground)' }} formatter={(v) => format(Number(v))} />
                            <Bar dataKey="value" isAnimationActive={false}>
                                {data.map(d => <Cell key={d.pipeline} fill={COLORS[d.pipeline]} />)}
                            </Bar>
                        </BarChart>
                    </ResponsiveContainer>
                </div>
            </CardContent>
        </Card>
    );
}

export default function EvalsPage() {
    const pipelines = orderedPipelines(summary);
    const ran = pipelines.filter(p => p.data);
    const rows = metricRows(summary);
    const extra = hasRunMetrics(summary);
    const cl = costLatencyData(summary);
    const placeholders = placeholderTiers(summary);
    const label = `Grouped bar chart of ${rows.map(r => r.label.toLowerCase()).join(', ')} as percentages for ${ran.map(p => p.name).join(', ') || 'no pipelines'}. The table below has the exact values.`;

    return (
        <Page title="Model tiers" subtitle="Eval results per pipeline against the answer key. Generated by npm run sync-evals.">
            {ran.length === 0 ? (
                <p className="text-sm text-muted-foreground">No eval results yet. Run an eval, then npm run sync-evals.</p>
            ) : (
                <>
                    <div className="grid gap-4 md:grid-cols-2">
                        <GateCard title="False auto-resolutions" rule="Must be 0. The agents never close a mismatch they should have escalated." gates={falseAutoGates(summary)} />
                        <GateCard title="Difference after approvals" rule="Should be 0.00 once every escalation is approved as drafted." gates={differenceGates(summary)} />
                    </div>
                    <p className="text-sm text-muted-foreground">Correctness gates are enforced by code; tiers differ in latency, tokens and cost.</p>
                    <Card>
                        <CardHeader><CardTitle className="text-base">Accuracy by metric</CardTitle></CardHeader>
                        <CardContent>
                            <div role="img" aria-label={label} className="h-72 w-full text-muted-foreground">
                                <ResponsiveContainer width="100%" height="100%">
                                    <BarChart data={chartData(summary)} margin={{ top: 8, right: 8, bottom: 8, left: 0 }} accessibilityLayer={false}>
                                        <CartesianGrid vertical={false} stroke="var(--border)" />
                                        <XAxis dataKey="metric" tick={{ fill: 'currentColor', fontSize: 12 }} stroke="var(--border)" />
                                        <YAxis domain={[0, 100]} unit="%" tick={{ fill: 'currentColor', fontSize: 12 }} stroke="var(--border)" />
                                        <Tooltip cursor={{ fill: 'var(--muted)' }} contentStyle={{ background: 'var(--card)', border: '1px solid var(--border)', color: 'var(--foreground)' }} formatter={(v) => `${v}%`} />
                                        <Legend />
                                        {ran.map(p => <Bar key={p.name} dataKey={p.name} fill={COLORS[p.name]} isAnimationActive={false} />)}
                                    </BarChart>
                                </ResponsiveContainer>
                            </div>
                        </CardContent>
                    </Card>
                    {cl.latency.length > 0 || cl.cost.length > 0 ? (
                        <div className="grid gap-4 md:grid-cols-2">
                            {cl.latency.length > 0 && <MiniChart title="Latency (s)" unit=" s" data={cl.latency} format={v => `${Math.round(v * 10) / 10} s`} />}
                            {cl.cost.length > 0 && <MiniChart title="Cost (USD)" unit="" data={cl.cost} format={v => `$${v}`} />}
                        </div>
                    ) : <p className="text-xs text-muted-foreground">Latency and cost appear after the tier runs.</p>}
                    
                    <div className="overflow-x-auto rounded-lg border">
                        <Table>
                            <TableHeader>
                                <TableRow>
                                    <TableHead scope="col">Metric (hit/total)</TableHead>
                                    {pipelines.map(p => <TableHead key={p.name} scope="col">{p.name}</TableHead>)}
                                </TableRow>
                            </TableHeader>
                            <TableBody>
                                {rows.map(r => (
                                    <TableRow key={r.key}>
                                        <TableHead scope="row" className="font-medium">{r.label}</TableHead>
                                        {pipelines.map(p => <TableCell key={p.name}>{r.values[p.name] ? formatRatio(r.values[p.name]!) : NOT_RUN}</TableCell>)}
                                    </TableRow>
                                ))}
                                <TableRow>
                                    <TableHead scope="row" className="font-medium">False auto-resolutions</TableHead>
                                    {pipelines.map(p => <TableCell key={p.name}>{p.data ? p.data.false_auto_resolutions : NOT_RUN}</TableCell>)}
                                </TableRow>
                                <TableRow>
                                    <TableHead scope="row" className="font-medium">Final difference (escalations pending)</TableHead>
                                    {pipelines.map(p => <TableCell key={p.name} className="font-mono">{p.data ? p.data.final_difference : NOT_RUN}</TableCell>)}
                                </TableRow>
                                <TableRow>
                                    <TableHead scope="row" className="font-medium">Difference after approvals</TableHead>
                                    {pipelines.map(p => <TableCell key={p.name} className="font-mono">{p.data ? p.data.difference_after_approvals ?? NA : NOT_RUN}</TableCell>)}
                                </TableRow>
                                <TableRow>
                                    <TableHead scope="row" className="font-medium">Expected difference</TableHead>
                                    {pipelines.map(p => <TableCell key={p.name} className="font-mono">{p.data ? p.data.expected_difference ?? NA : NOT_RUN}</TableCell>)}
                                </TableRow>
                                {extra.latency && (
                                    <TableRow>
                                        <TableHead scope="row" className="font-medium">Latency</TableHead>
                                        {pipelines.map(p => <TableCell key={p.name}>{p.data ? formatLatency(p.data.latency_ms) ?? NA : NOT_RUN}</TableCell>)}
                                    </TableRow>
                                )}
                                {extra.tokens && (
                                    <TableRow>
                                        <TableHead scope="row" className="font-medium">Tokens</TableHead>
                                        {pipelines.map(p => <TableCell key={p.name}>{p.data ? formatTokens(p.data) ?? NA : NOT_RUN}</TableCell>)}
                                    </TableRow>
                                )}
                                {extra.calls && (
                                    <TableRow>
                                        <TableHead scope="row" className="font-medium">Model calls</TableHead>
                                        {pipelines.map(p => <TableCell key={p.name}>{p.data ? formatCalls(p.data) ?? NA : NOT_RUN}</TableCell>)}
                                    </TableRow>
                                )}
                                {extra.cost && (
                                    <TableRow>
                                        <TableHead scope="row" className="font-medium">Estimated cost</TableHead>
                                        {pipelines.map(p => <TableCell key={p.name}>{p.data ? formatCost(p.data.cost_usd) ?? NA : NOT_RUN}</TableCell>)}
                                    </TableRow>
                                )}
                            </TableBody>
                        </Table>
                    </div>
                    {extra.cost && placeholders.length > 0 && <p className="text-xs text-muted-foreground">Placeholder price: the {placeholders.join(', ')} cost {placeholders.length === 1 ? 'is' : 'are'} an estimate, not a published rate.</p>}
                </>
            )}
        </Page>
    );
}
